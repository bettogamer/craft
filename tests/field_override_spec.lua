local Craft = LibStub("Craft-2.0")

local function newField()
    local parent = CreateFrame("Frame"); parent:SetSize(300, 300)
    local ctrl = CreateFrame("Frame"); ctrl:SetSize(200, 20)
    return Craft.Field:Create(parent, { label = "Color", control = ctrl, width = 200 })
end

describe("Craft.Field override mark (FR-131, con Weave)", function()

    it("aparece con el fundido: visible y clicable al activarse", function()
        local field = newField()
        field:SetOverridden(true)
        assert.is_not_nil(field._markOn)          -- camino Weave
        assert.is_true(field._mark:IsShown())
        assert.is_true(field._mark:IsMouseEnabled())
    end)

    it("al salir deja de recibir clics en el acto, sin esperar al fade", function()
        local field = newField()
        field:SetOverridden(true)
        field:SetOverridden(false)
        assert.is_false(field._mark:IsMouseEnabled())
        assert.is_false(field:IsOverridden())
    end)

    it("icono rotate-ccw en t.primary (16px)", function()
        local field = newField()
        field:SetOverridden(true)
        local t = Craft.Theme.get()
        local c = field._mark._icon._vertexColor
        assert.equals(t.primary.r, c.r); assert.equals(t.primary.g, c.g)
        assert.equals(16, field._mark._icon:GetWidth())
        assert.equals(20, field._mark:GetWidth())
    end)

    it("hover pinta el icono en t.foreground", function()
        local field = newField()
        field:SetOverridden(true)
        field._mark:_fire("OnEnter")
        local t = Craft.Theme.get()
        assert.equals(t.foreground.r, field._mark._icon._vertexColor.r)
        field._mark:_fire("OnLeave")
        assert.equals(t.primary.r, field._mark._icon._vertexColor.r)
    end)

    it("Destroy libera los efectos de la marca", function()
        local field = newField()
        field:SetOverridden(true)
        field:Destroy()
        assert.equals(0, #field._effects)
        assert.is_nil(field._mark)
    end)
end)
